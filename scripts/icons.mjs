#!/usr/bin/env node
// Builds extension/icons.js from the Lucide icon set (lucide-static, ISC license).
// Extensions can't load code from the internet, so the few icons we use are copied
// in. To add an icon: put its Lucide name in NAMES (see https://lucide.dev/icons),
// then run `npm run icons`.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const PKG = path.dirname(require.resolve('lucide-static/package.json'));
const { version } = JSON.parse(fs.readFileSync(path.join(PKG, 'package.json'), 'utf8'));

export const NAMES = [
  'grip-vertical', 'mouse-pointer-2', 'pen-line', 'type', 'camera', 'trash-2', 'circle-help', 'x',
  'highlighter', 'eraser', 'arrow-left-right', 'move', 'copy', 'download', 'check', 'coffee',
  'puzzle', 'pin', 'arrow-right',
];

// Just the shapes inside each <svg>; the extension wraps them in its own <svg> tag.
export function shapes(name) {
  const svg = fs.readFileSync(path.join(PKG, 'icons', `${name}.svg`), 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  return inner.replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>');
}

export function build() {
  const body = NAMES.map((n) => `  '${n}': '${shapes(n)}',`).join('\n');
  return `// Generated by scripts/icons.mjs from Lucide (lucide-static v${version}), ISC license:
// see LICENSE-lucide.txt. Do not edit by hand; run \`npm run icons\`.
globalThis.VHL_ICONS = {
${body}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(ROOT, 'extension', 'icons.js'), build());
  fs.copyFileSync(path.join(PKG, 'LICENSE'), path.join(ROOT, 'extension', 'LICENSE-lucide.txt'));
  console.log(`✓ extension/icons.js: ${NAMES.length} Lucide icons (v${version})`);
}
